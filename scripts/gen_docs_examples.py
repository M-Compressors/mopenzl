#!/usr/bin/env python3
"""Generate tests/docs_examples.rs from the Rust examples of the user docs.

Every fenced ```rust block of README.md and docs/*.md is a complete program
with a `fn main`. A line `<!-- cfg: <predicate>, ... -->` right before the
block lists the `cfg` predicates (all must hold) the example needs; without
one the example needs only `compression` and `decompression`.

    python3 scripts/gen_docs_examples.py           # rewrite the test file
    python3 scripts/gen_docs_examples.py --check   # fail if it is stale

`tests/docs_examples.rs` then compiles and runs each example verbatim.
"""

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "tests" / "docs_examples.rs"
FILES = ["README.md"] + sorted(
    str(p.relative_to(ROOT)) for p in (ROOT / "docs").glob("*.md")
)
BLOCK = re.compile(
    r"(?:<!-- cfg: (?P<cfg>[^>]*?) -->\n)?```rust\n(?P<code>.*?)```", re.S
)


def fmt(code):
    """The snippet as rustfmt writes it (unchanged if rustfmt rejects it)."""
    done = subprocess.run(
        ["rustfmt", "--edition", "2024"], input=code, capture_output=True, text=True
    )
    return done.stdout if done.returncode == 0 else code


def sync():
    """Rewrite every example in the markdown the way rustfmt formats it."""
    for name in FILES:
        path = ROOT / name
        text = path.read_text()
        text = BLOCK.sub(
            lambda m: (f"<!-- cfg: {m.group('cfg')} -->\n" if m.group("cfg") else "")
            + "```rust\n" + fmt(m.group("code")) + "```",
            text,
        )
        path.write_text(text)


def examples():
    for name in FILES:
        text = (ROOT / name).read_text()
        for index, match in enumerate(BLOCK.finditer(text), 1):
            cfg = match.group("cfg")
            preds = [p.strip() for p in cfg.split(";")] if cfg else []
            stem = re.sub(r"\W+", "_", name.removesuffix(".md")).strip("_").lower()
            yield f"{stem}_{index}", name, preds, match.group("code")


def render():
    out = [
        "//! Every Rust example of README.md and docs/*.md, verbatim.",
        "//!",
        "//! Generated by `scripts/gen_docs_examples.py`; edit the markdown and",
        "//! rerun the script. `docs_examples_are_current` fails when they differ.",
        '#![cfg(all(feature = "compression", feature = "decompression"))]',
        "",
    ]
    for ident, name, preds, code in examples():
        gate = preds[0] if len(preds) == 1 else ", ".join(preds)
        cfg = f"#[cfg({gate})]" if len(preds) == 1 else f"#[cfg(all({gate}))]"
        out.append(f"/// Example {ident.rsplit('_', 1)[1]} of `{name}`.")
        if gate:
            out.append(cfg)
        out.append("#[rustfmt::skip]")
        out.append(f"mod {ident} {{")
        out.extend(f"    {line}" if line.strip() else "" for line in code.rstrip().split("\n"))
        out.append("")
        out.append("    #[test]")
        out.append("    fn runs() {")
        out.append("        main().unwrap();")
        out.append("    }")
        out.append("}")
        out.append("")
    out.append("/// The examples in the markdown are the ones compiled above.")
    out.append("#[test]")
    out.append("fn docs_examples_are_current() {")
    out.append('    let source = include_str!("docs_examples.rs");')
    out.append("    let squash = |text: &str| -> String {")
    out.append("        text.lines()")
    out.append("            .map(str::trim)")
    out.append("            .filter(|l| !l.is_empty())")
    out.append("            .collect::<Vec<_>>()")
    out.append('            .join("\\n")')
    out.append("    };")
    out.append("    let source = squash(source);")
    out.append("    for (name, text) in [")
    for name in FILES:
        out.append(f'        ("{name}", include_str!("../{name}")),')
    out.append("    ] {")
    out.append('        for block in text.split("```rust\\n").skip(1) {')
    out.append('            let code = squash(block.split("```").next().unwrap_or_default());')
    out.append('            assert!(source.contains(&code), "{name}: stale example:\\n{code}");')
    out.append("        }")
    out.append("    }")
    out.append("}")
    out.append("")
    return "\n".join(out)


def main():
    if "--check" not in sys.argv:
        sync()
    text = render()
    if "--check" in sys.argv:
        done = subprocess.run(["rustfmt", "--edition", "2024"], input=text, capture_output=True, text=True)
        text = done.stdout if done.returncode == 0 else text
        if OUT.read_text() != text:
            sys.exit("tests/docs_examples.rs is stale: run scripts/gen_docs_examples.py")
        return
    OUT.write_text(text)
    subprocess.run(["rustfmt", "--edition", "2024", str(OUT)], check=False)


if __name__ == "__main__":
    main()
